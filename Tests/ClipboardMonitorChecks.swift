#if STANDALONE_CHECKS
import AppKit
import CpinCore

@main
struct ClipboardMonitorChecks {
    @MainActor
    static func main() throws {
        let directory = FileManager.default.temporaryDirectory.appendingPathComponent("cpin-monitor-check-\(UUID().uuidString)")
        let board = NSPasteboard(name: NSPasteboard.Name("cpin-check-\(UUID().uuidString)"))
        defer {
            board.releaseGlobally()
            try? FileManager.default.removeItem(at: directory)
        }
        let history = try ClipboardHistory(directory: directory)
        var errors: [String] = []
        func putText(_ text: String) {
            board.clearContents()
            precondition(board.setString(text, forType: .string))
        }
        putText("before start")
        let monitor = ClipboardMonitor(history: history, pasteboard: board) { errors.append($0) }
        monitor.start()
        defer { monitor.stop() }
        monitor.captureChanges()
        precondition(history.items.isEmpty, "Must ignore preexisting contents")

        putText("  original text\n")
        monitor.captureChanges()
        precondition(history.items.count == 1 && history.items[0].text == "  original text\n")
        let textItem = history.items[0]
        putText("  original text\n")
        monitor.captureChanges()
        precondition(history.items.count == 1 && history.items[0].id == textItem.id, "Duplicate identity must survive")

        monitor.isPaused = true
        putText("paused and polled")
        monitor.captureChanges()
        putText("paused but not polled")
        monitor.isPaused = false
        monitor.captureChanges()
        precondition(history.items.count == 1, "Resume must not import paused contents")
        putText("after resume")
        monitor.captureChanges()
        precondition(history.items.count == 2)

        for marker in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"] {
            putText("sensitive \(marker)")
            precondition(board.setData(Data(), forType: NSPasteboard.PasteboardType(marker)))
            monitor.captureChanges()
            precondition(history.items.count == 2, "Must skip \(marker)")
        }
        putText("file label")
        precondition(board.setString("file:///tmp/example.txt", forType: .fileURL))
        monitor.captureChanges()
        precondition(history.items.count == 2)

        let beforeWrite = history.items
        try monitor.write(textItem)
        precondition(board.string(forType: .string) == textItem.text)
        monitor.captureChanges()
        precondition(history.items == beforeWrite, "Self writes must not reorder or update timestamps")
        putText(String(repeating: "x", count: 1_048_577))
        monitor.captureChanges()
        precondition(history.items.count == 2 && errors.isEmpty, "Oversize text must be silently ignored")

        let bitmap = NSBitmapImageRep(bitmapDataPlanes: nil, pixelsWide: 3, pixelsHigh: 2, bitsPerSample: 8,
                                      samplesPerPixel: 4, hasAlpha: true, isPlanar: false, colorSpaceName: .deviceRGB,
                                      bytesPerRow: 0, bitsPerPixel: 0)!
        for x in 0..<3 { for y in 0..<2 { bitmap.setColor(NSColor(deviceRed: 0.1, green: 0.3, blue: 0.9, alpha: 1), atX: x, y: y) } }
        let png = bitmap.representation(using: .png, properties: [:])!
        board.clearContents()
        precondition(board.setData(png, forType: .png))
        monitor.captureChanges()
        let imageItem = history.items[0]
        precondition(imageItem.kind == .image && imageItem.pixelWidth == 3 && imageItem.pixelHeight == 2)
        let savedPNG = try Data(contentsOf: history.imageURL(for: imageItem)!)
        precondition(savedPNG == png, "PNG bytes must remain unchanged")
        let beforeImageWrite = history.items
        try monitor.write(imageItem)
        precondition(board.data(forType: .png) == png)
        monitor.captureChanges()
        precondition(history.items == beforeImageWrite)

        bitmap.setColor(NSColor(deviceRed: 0.9, green: 0.1, blue: 0.2, alpha: 1), atX: 0, y: 0)
        let tiff = bitmap.representation(using: .tiff, properties: [:])!
        board.clearContents()
        precondition(board.setData(tiff, forType: .tiff))
        monitor.captureChanges()
        let converted = history.items[0]
        precondition(converted.kind == .image && converted.id != imageItem.id)
        let convertedData = try Data(contentsOf: history.imageURL(for: converted)!)
        precondition(convertedData.starts(with: [137, 80, 78, 71, 13, 10, 26, 10]))
        let decoded = NSBitmapImageRep(data: convertedData)!
        precondition(decoded.pixelsWide == 3 && decoded.pixelsHigh == 2)
        precondition(errors.isEmpty, "Unexpected capture errors: \(errors)")
        print("Clipboard monitor checks passed (isolated named pasteboard).")
    }
}
#endif
