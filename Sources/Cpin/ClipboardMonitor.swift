import CpinCore

import AppKit
import ImageIO

@MainActor
final class ClipboardMonitor {
    var isPaused = false {
        didSet { if oldValue != isPaused { changeCount = pasteboard.changeCount } }
    }
    private let pasteboard: NSPasteboard
    private let history: ClipboardHistory
    private let onError: (String) -> Void
    private var timer: Timer?
    private var changeCount: Int
    private let maximumBytes = 16 * 1024 * 1024

    init(history: ClipboardHistory, pasteboard: NSPasteboard = .general, onError: @escaping (String) -> Void) {
        self.history = history
        self.pasteboard = pasteboard
        self.changeCount = pasteboard.changeCount
        self.onError = onError
    }

    func start() {
        stop()
        changeCount = pasteboard.changeCount
        let timer = Timer(timeInterval: 0.6, repeats: true) { [weak self] _ in
            Task { @MainActor [weak self] in self?.captureChanges() }
        }
        self.timer = timer
        RunLoop.main.add(timer, forMode: .common)
    }

    func stop() { timer?.invalidate(); timer = nil }
    deinit { timer?.invalidate() }

    func captureChanges() {
        let board = pasteboard
        guard board.changeCount != changeCount else { return }
        changeCount = board.changeCount
        guard !isPaused else { return }
        let excluded = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"]
        let types = board.types ?? []
        guard !excluded.contains(where: { types.contains(NSPasteboard.PasteboardType($0)) }),
              !types.contains(.fileURL) else { return }
        let app = NSWorkspace.shared.frontmostApplication
        let name = app?.localizedName ?? "未知应用"
        do {
            if types.contains(.png) || types.contains(.tiff) {
                let isPNG = types.contains(.png)
                guard let data = board.data(forType: isPNG ? .png : .tiff),
                      data.count <= maximumBytes,
                      let source = CGImageSourceCreateWithData(data as CFData, [kCGImageSourceShouldCache: false] as CFDictionary),
                      let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
                      let width = (properties[kCGImagePropertyPixelWidth] as? NSNumber)?.intValue,
                      let height = (properties[kCGImagePropertyPixelHeight] as? NSNumber)?.intValue,
                      width > 0, height > 0, width <= 64_000_000 / height else { return }
                let png: Data
                if isPNG {
                    png = data
                } else {
                    guard let image = CGImageSourceCreateImageAtIndex(source, 0, nil),
                          let encoded = NSBitmapImageRep(cgImage: image).representation(using: .png, properties: [:]),
                          encoded.count <= maximumBytes else { return }
                    png = encoded
                }
                _ = try history.addImage(png, width: width, height: height,
                                         sourceName: name, sourceBundleIdentifier: app?.bundleIdentifier)
            } else if let text = board.string(forType: .string), text.utf8.count <= 1024 * 1024 {
                _ = try history.addText(text, sourceName: name, sourceBundleIdentifier: app?.bundleIdentifier)
            }
        } catch { onError("无法保存剪切板内容：\(error.localizedDescription)") }
    }

    func write(_ item: ClipItem) throws {
        let board = pasteboard
        if item.kind == .image {
            guard let url = history.imageURL(for: item) else { throw ClipboardError.missingImage }
            let data = try Data(contentsOf: url)
            board.clearContents()
            defer { changeCount = board.changeCount }
            guard board.setData(data, forType: .png) else { throw ClipboardError.writeFailed }
        } else {
            guard let text = item.text else { throw ClipboardError.writeFailed }
            board.clearContents()
            defer { changeCount = board.changeCount }
            guard board.setString(text, forType: .string) else { throw ClipboardError.writeFailed }
        }
    }

    private enum ClipboardError: LocalizedError {
        case missingImage, writeFailed
        var errorDescription: String? {
            switch self {
            case .missingImage: return "图片文件不存在"
            case .writeFailed: return "无法写入剪切板"
            }
        }
    }
}
